/// Reads a real Claude log end to end; skipped unless `SWITCHBOARD_LIVE_CLAUDE_LOG` names one.
#[test]
fn a_real_log_pages_back_to_its_start() {
    let Ok(path) = std::env::var("SWITCHBOARD_LIVE_CLAUDE_LOG") else {
        return;
    };
    let path = PathBuf::from(path);
    let mut page = read_page(&path, None, None).unwrap();
    let mut kinds = std::collections::BTreeMap::<String, usize>::new();
    let mut pages = 1;
    loop {
        for i in &page.items {
            *kinds.entry(i.kind.clone()).or_default() += 1;
        }
        if page.start == 0 {
            break;
        }
        let back = read_page(&path, None, Some(page.start)).unwrap();
        assert!(
            back.end == page.start && back.start < page.start,
            "always makes progress"
        );
        page = back;
        pages += 1;
    }
    eprintln!("{pages} pages: {kinds:?}");
    assert!(kinds.contains_key("user") && kinds.contains_key("assistant"));
}

