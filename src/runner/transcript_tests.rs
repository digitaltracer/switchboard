use serde_json::json;

use super::*;

fn line(v: Value) -> String {
    format!("{v}\n")
}

fn user(uuid: &str, content: Value) -> String {
    line(
        json!({"type": "user", "uuid": uuid, "timestamp": "2026-10-26T09:00:00Z",
                "isSidechain": false, "message": {"role": "user", "content": content}}),
    )
}

fn assistant(uuid: &str, blocks: Value) -> String {
    line(
        json!({"type": "assistant", "uuid": uuid, "isSidechain": false,
                "message": {"role": "assistant", "content": blocks}}),
    )
}

/// A short conversation with the noise a real log carries around it.
fn conversation() -> String {
    [
        line(json!({"type": "permission-mode", "permissionMode": "auto"})),
        user("u1", json!("in udp-backend, find errors from the last 12 hours")),
        user("u0", json!("<local-command-caveat>Caveat: generated by a local command</local-command-caveat>")),
        line(json!({"type": "user", "uuid": "meta", "isMeta": true, "message": {"content": "hidden"}})),
        assistant("a1", json!([
            {"type": "thinking", "thinking": "private", "signature": "s"},
            {"type": "text", "text": "I'll look at the logs."},
        ])),
        assistant("a2", json!([{"type": "tool_use", "id": "t1", "name": "Bash",
                                "input": {"command": "cargo test -p core\necho done"}}])),
        line(json!({"type": "api-request-blob", "message": {"content": [{"type": "text", "text": "\"type\":\"user\" copy"}]}})),
        user("r1", json!([{"type": "tool_result", "tool_use_id": "t1", "content": "test result: ok", "is_error": false}])),
        assistant("a3", json!([{"type": "tool_use", "id": "t2",
                                "name": "mcp__elasticsearch-app-mcp-server__esql", "input": {"query": "FROM logs"}}])),
        user("r2", json!([{"type": "tool_result", "tool_use_id": "t2",
                           "content": [{"type": "text", "text": "no rows"}], "is_error": true}])),
        line(json!({"type": "assistant", "uuid": "side", "isSidechain": true,
                    "message": {"content": [{"type": "text", "text": "a subagent's own turn"}]}})),
        user("b1", json!("<bash-input>git status</bash-input>")),
        line(json!({"type": "system", "uuid": "c1", "subtype": "compact_boundary"})),
        assistant("a4", json!([{"type": "text", "text": "No errors in the last 12 hours."}])),
    ]
    .concat()
}

fn log(text: &str) -> (tempfile::TempDir, PathBuf) {
    let dir = tempfile::tempdir().unwrap();
    let path = dir.path().join("log.jsonl");
    std::fs::write(&path, text).unwrap();
    (dir, path)
}

fn shown(p: &TranscriptPage) -> Vec<(String, Option<String>)> {
    p.items
        .iter()
        .map(|i| (i.kind.clone(), i.text.clone()))
        .collect()
}

#[test]
fn a_log_reads_as_a_conversation_without_the_noise() {
    let (_d, path) = log(&conversation());
    let page = read_page(&path, None, None).unwrap();
    let s = |k: &str, t: &str| (k.to_owned(), Some(t.to_owned()));
    assert_eq!(
        shown(&page),
        [
            s("user", "in udp-backend, find errors from the last 12 hours"),
            s("assistant", "I'll look at the logs."),
            s("tool", "Ran cargo test -p core"),
            s("tool", "Used elasticsearch-app-mcp-server · esql"),
            s("note", "! git status"),
            s("note", "Earlier messages were compacted."),
            s("assistant", "No errors in the last 12 hours."),
        ]
    );
    let bash = &page.items[2];
    assert_eq!(
        (bash.id.as_str(), bash.done, bash.failed),
        ("t1", true, false)
    );
    assert_eq!(bash.output.as_deref(), Some("test result: ok"));
    assert_eq!(bash.tool.as_deref(), Some("Bash"));
    assert!(bash.input.as_deref().unwrap().contains("cargo test"));
    let mcp = &page.items[3];
    assert_eq!(
        (mcp.done, mcp.failed, mcp.output.as_deref()),
        (true, true, Some("no rows"))
    );
    assert_eq!(page.items[0].at.as_deref(), Some("2026-10-26T09:00:00Z"));
    assert_eq!(
        (page.start, page.end),
        (0, std::fs::metadata(&path).unwrap().len())
    );
}

#[test]
fn pages_continue_after_and_go_back_before_on_line_boundaries() {
    let text = conversation();
    let (_d, path) = log(&text);
    let first = read_page(&path, None, None).unwrap();

    // A half-written line waits for the next page.
    let more = assistant("a5", json!([{"type": "text", "text": "Anything else?"}]));
    let (done, partial) = more.split_at(more.len() / 2);
    std::fs::write(&path, format!("{text}{done}")).unwrap();
    let next = read_page(&path, Some(first.end), None).unwrap();
    assert!(next.items.is_empty());
    assert_eq!((next.start, next.end), (first.end, first.end));
    std::fs::write(&path, format!("{text}{done}{partial}")).unwrap();
    let next = read_page(&path, Some(first.end), None).unwrap();
    assert_eq!(
        next.start, first.end,
        "continues exactly where the last page ended"
    );
    assert_eq!(
        shown(&next),
        [("assistant".into(), Some("Anything else?".into()))]
    );

    // A result whose call was on an earlier page comes alone, for the phone to join.
    let result = user(
        "r3",
        json!([{"type": "tool_result", "tool_use_id": "t1", "content": "again"}]),
    );
    let len = std::fs::metadata(&path).unwrap().len();
    std::fs::write(&path, format!("{text}{done}{partial}{result}")).unwrap();
    let joined = read_page(&path, Some(len), None).unwrap();
    let r = &joined.items[0];
    assert_eq!(
        (
            r.id.as_str(),
            r.text.as_deref(),
            r.done,
            r.output.as_deref()
        ),
        ("t1", None, true, Some("again"))
    );

    // Going back stops at the page's start and never splits a line.
    let back = read_page(&path, None, Some(first.end)).unwrap();
    assert_eq!(back.end, first.end);
    assert_eq!(shown(&back), shown(&first));
}

#[test]
fn a_big_log_is_read_from_its_end_starting_on_a_whole_line() {
    let filler = line(json!({"type": "api-request-blob", "pad": "x".repeat(4096)}));
    let text = format!("{}{}", filler.repeat(400), conversation());
    let (_d, path) = log(&text);
    let page = read_page(&path, None, None).unwrap();
    assert!(page.start > 0 && page.start < text.len() as u64);
    assert_eq!(
        text.as_bytes()[page.start as usize - 1],
        b'\n',
        "starts on a line"
    );
    assert_eq!(page.items.len(), 7);
    let back = read_page(&path, None, Some(page.start)).unwrap();
    assert!(back.items.is_empty() && back.end == page.start);
}

#[test]
fn a_line_longer_than_a_page_is_skipped_unread() {
    let huge = line(json!({"type": "api-request-blob", "pad": "x".repeat(WINDOW as usize * 2)}));
    let before = user("u1", json!("before the big line"));
    let after = user("u2", json!("after the big line"));
    let text = format!("{before}{huge}{after}");
    let (_d, path) = log(&text);
    let latest = read_page(&path, None, None).unwrap();
    assert_eq!(
        shown(&latest),
        [("user".into(), Some("after the big line".into()))]
    );
    let back = read_page(&path, None, Some(latest.start)).unwrap();
    assert_eq!(
        shown(&back),
        [("user".into(), Some("before the big line".into()))]
    );
    assert_eq!((back.start, back.end), (0, latest.start));

    // A huge line still being written ends nothing yet.
    let (_d, path) = log(&format!("{before}{}", &huge[..huge.len() - 1]));
    let page = read_page(&path, None, None).unwrap();
    assert_eq!(
        shown(&page),
        [("user".into(), Some("before the big line".into()))]
    );
    assert_eq!(page.end, before.len() as u64);
}

