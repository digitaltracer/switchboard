/// Reads a real Codex log; skipped unless `SWITCHBOARD_LIVE_CODEX_LOG` names one.
#[test]
fn a_real_codex_log_reads() {
    let Ok(path) = std::env::var("SWITCHBOARD_LIVE_CODEX_LOG") else {
        return;
    };
    let page = read_page(Path::new(&path), None, None).unwrap();
    let mut kinds = std::collections::BTreeMap::<String, usize>::new();
    for i in &page.items {
        *kinds.entry(i.kind.clone()).or_default() += 1;
    }
    let ran = page
        .items
        .iter()
        .filter(|i| {
            i.text
                .as_deref()
                .is_some_and(|t| t.starts_with("Ran ") && t != "Ran a command")
        })
        .count();
    eprintln!("{kinds:?}, {ran} commands named");
    assert!(kinds.contains_key("user") && kinds.contains_key("tool"));
}

#[test]
fn the_claude_running_in_the_pane_names_its_own_session() {
    let dir = tempfile::tempdir().unwrap();
    let sessions = dir.path().join("sessions");
    std::fs::create_dir(&sessions).unwrap();
    let record = |pid: u32, id: &str| {
        std::fs::write(
            sessions.join(format!("{pid}.json")),
            json!({"pid": pid, "sessionId": id, "cwd": "/repo"}).to_string(),
        )
        .unwrap()
    };
    record(31681, "5fdba77e-live");
    // A record whose pid doesn't match its file name is someone else's.
    std::fs::write(
        sessions.join("400.json"),
        json!({"pid": 401, "sessionId": "wrong"}).to_string(),
    )
    .unwrap();

    // The pane's shell and MCP servers have no record; its Claude does.
    assert_eq!(
        live_claude_session(dir.path(), &[60021, 400, 31681]).as_deref(),
        Some("5fdba77e-live")
    );
    assert_eq!(live_claude_session(dir.path(), &[400, 9]), None);
    assert_eq!(
        live_claude_session(&dir.path().join("missing"), &[31681]),
        None
    );
}

#[test]
fn edits_say_how_many_lines_they_add_and_remove() {
    let text = [
        assistant("a1", json!([{"type": "tool_use", "id": "e1", "name": "Edit",
            "input": {"file_path": "/r/a.py", "old_string": "x = 1\ny = 2", "new_string": "x = 1\ny = 3\nz = 4"}}])),
        assistant("a2", json!([{"type": "tool_use", "id": "e2", "name": "MultiEdit",
            "input": {"file_path": "/r/b.py", "edits": [
                {"old_string": "a", "new_string": "b\nc"}, {"old_string": "d\ne", "new_string": ""}]}}])),
        assistant("a3", json!([{"type": "tool_use", "id": "e3", "name": "Write",
            "input": {"file_path": "/r/c.py", "content": "one\ntwo\nthree\n"}}])),
        assistant("a4", json!([{"type": "tool_use", "id": "e4", "name": "Bash", "input": {"command": "ls"}}])),
    ]
    .concat();
    let (_d, path) = log(&text);
    let page = read_page(&path, None, None).unwrap();
    let counts: Vec<_> = page.items.iter().map(|i| (i.added, i.removed)).collect();
    assert_eq!(
        counts,
        vec![
            (Some(3), Some(2)),
            (Some(2), Some(3)),
            (Some(3), Some(0)),
            (None, None)
        ]
    );
}

